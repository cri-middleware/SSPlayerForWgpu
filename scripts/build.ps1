#!/usr/bin/env pwsh
#
# Build the ssplayer-wgpu library for one platform and collect its artifacts.
# PowerShell twin of build.sh.
#
#   scripts/build.ps1                            # host, release
#   scripts/build.ps1 platform=web build=debug   # wasm for examples/web, fast build
#
# Same shape as the sibling players' build-runtime.ps1: build the library, then
# gather the library, its public header and its licence into one project-local
# tree, so release-<platform>.ps1 packages from a known layout instead of knowing
# where each toolchain drops its output.
#
#   bin/include/ssplayer_wgpu.h                 (ffi=yes, regenerated by cbindgen)
#   bin/LICENSE.md
#   bin/libs/<platform>/<arch>/ssplayer_wgpu.{lib,dll} | libssplayer_wgpu.{a,dylib,so}
#   pkg/                                        (wasm-pack --target web; its own
#                                                convention, and already a package)
#   examples/web/wasm/                          (deploy=yes)
#
# Playback data is not this script's business at all: converting the SDK's test
# projects into .ssab -- and building the ssconverter-cli that does it -- is
# scripts/deploy-examples.ps1, which also deploys both export modes to the demo.
$ErrorActionPreference = "Stop"

$APP = Split-Path -Leaf $PSCommandPath
$ROOT_DIR = Split-Path -Parent (Split-Path -Parent $PSCommandPath)
$BIN_DIR = Join-Path $ROOT_DIR "bin"

# Plain stderr + an exit code, rather than Write-Error's stack trace: this is a
# build script, and build.sh answers the same mistakes the same way (2 = bad
# usage, 1 = the environment is not ready).
function Fail {
    param([string] $Message, [int] $Code = 1)
    [Console]::Error.WriteLine("${APP}: $Message")
    exit $Code
}

if ($IsWindows) { $HOST_OS = "windows" } elseif ($IsMacOS) { $HOST_OS = "macos" } else { $HOST_OS = "linux" }
$HOST_ARCH = [System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString().ToLower()
if ($HOST_ARCH -eq "x64") { $HOST_ARCH = "x86_64" }

# --- options --------------------------------------------------------------
$opts = [ordered]@{
    platform = "host"
    build    = "release"
    ffi      = "yes"
    deploy   = "yes"
}

function Show-Usage {
    Write-Host "Usage: $APP [options]"
    Write-Host "$APP options:"
    Write-Host "  platform=<host|web>     Target platform (default: host)"
    Write-Host "                          host = Rust library (+ the C face); web = wasm/js face"
    Write-Host "  build=<release|debug>   Build profile (default: release)"
    Write-Host "  ffi=<yes|no>            host only: also build --features ffi, which regenerates"
    Write-Host "                          libs/ssplayer-wgpu-ffi/include/ssplayer_wgpu.h (default: yes)"
    Write-Host "  deploy=<yes|no>         web only: copy the wasm package into examples/web"
    Write-Host "                          (default: yes)"
    Write-Host "  -h | --help             Show this help"
    Write-Host ""
    Write-Host "host artifacts are collected under bin/, the web package into pkg/. This is"
    Write-Host "$HOST_OS/$HOST_ARCH and the script does not cross-compile; macos/windows/linux"
    Write-Host "are accepted as aliases for platform=host when they name the host itself."
    Write-Host ""
    Write-Host "Playback data (.ssab) is scripts/deploy-examples.ps1, not this script."
}

foreach ($item in $args) {
    if ($item -in "-h", "--help", "help") {
        Show-Usage
        exit 0
    } elseif ($item -match "=") {
        $key, $value = $item -split "=", 2
        if (-not $opts.Contains($key)) {
            Fail "unknown option '$key' (see $APP --help)" 2
        }
        $opts[$key] = $value.ToLower()
    } else {
        Fail "unknown argument '$item' (options are key=value; see $APP --help)" 2
    }
}

switch ($opts.platform) {
    { $_ -in "host", "native" } { $opts.platform = "host" }
    "web" { }
    { $_ -in "macos", "windows", "win", "linux" } {
        $named = if ($_ -eq "win") { "windows" } else { $_ }
        if ($named -ne $HOST_OS) {
            Fail "platform=$named, but this is $HOST_OS; cross-compilation is not supported" 2
        }
        $opts.platform = "host"
    }
    default { Fail "platform must be host or web (got '$($opts.platform)')" 2 }
}

if ($opts.build -notin "release", "debug") { Fail "build must be release or debug (got '$($opts.build)')" 2 }
if ($opts.ffi -notin "yes", "no") { Fail "ffi must be yes or no (got '$($opts.ffi)')" 2 }
if ($opts.deploy -notin "yes", "no") { Fail "deploy must be yes or no (got '$($opts.deploy)')" 2 }

Write-Host "options"
Write-Host "  platform => $($opts.platform)"
Write-Host "  build    => $($opts.build)"
if ($opts.platform -eq "host") { Write-Host "  ffi      => $($opts.ffi)" }
if ($opts.platform -eq "web") { Write-Host "  deploy   => $($opts.deploy)" }
Write-Host ""

# --- preflight ------------------------------------------------------------
# ssruntime / ssab are path dependencies into the submodule, so nothing builds
# without it.
if (!(Test-Path (Join-Path $ROOT_DIR "SpriteStudio-SDK/Cargo.toml"))) {
    [Console]::Error.WriteLine("${APP}: SpriteStudio-SDK submodule is not initialized")
    Fail "run 'git submodule update --init' first"
}
if (!(Get-Command cargo -ErrorAction SilentlyContinue)) {
    Fail "cargo not found (install a Rust toolchain: https://rustup.rs)"
}

function Invoke-Checked {
    param([string] $What, [scriptblock] $Body)
    & $Body
    if ($LASTEXITCODE -ne 0) { Fail "$What failed ($LASTEXITCODE)" $LASTEXITCODE }
}

function Reset-Dir {
    param([string] $Path)
    if (Test-Path $Path) { Remove-Item -Recurse -Force $Path }
    New-Item -ItemType Directory -Force -Path $Path > $null
}

# The library's own licence travels with the binaries, not the repository's.
function Copy-License {
    New-Item -ItemType Directory -Force -Path $BIN_DIR > $null
    Copy-Item -Force (Join-Path $ROOT_DIR "libs/ssplayer-wgpu/LICENSE.md") $BIN_DIR
}

# --- host -----------------------------------------------------------------
if ($opts.platform -eq "host") {
    $profileArgs = @()
    if ($opts.build -eq "release") { $profileArgs += "--release" }

    Write-Host ">> cargo build -p ssplayer-wgpu-ffi ($($opts.build))"
    Push-Location $ROOT_DIR
    try {
        Invoke-Checked "cargo build" { & cargo build -p ssplayer-wgpu-ffi --no-default-features --features embedded @profileArgs }

        if ($opts.ffi -eq "yes") {
            # No default command compiles src/ffi.rs or src/host.rs, so the C face
            # rots silently unless it is built explicitly. build.rs runs cbindgen in
            # the same pass, which is what keeps include/ssplayer_wgpu.h in step
            # with the API.
            Write-Host ">> cargo build -p ssplayer-wgpu-ffi ($($opts.build)) - regenerates include/ssplayer_wgpu.h"
            Invoke-Checked "cargo build -p ssplayer-wgpu-ffi" { & cargo build -p ssplayer-wgpu-ffi @profileArgs }
        }
    } finally {
        Pop-Location
    }

    # --- collect ----------------------------------------------------------
    $SRC_DIR = Join-Path $ROOT_DIR "target/$($opts.build)"
    $LIB_OUT_DIR = Join-Path $BIN_DIR "libs/$HOST_OS/$HOST_ARCH"
    Write-Host ">> collecting artifacts from target/$($opts.build) -> bin/libs/$HOST_OS/$HOST_ARCH"
    Reset-Dir $LIB_OUT_DIR

    # cargo emits every crate-type each build, but which names appear is the
    # platform's business (staticlib + cdylib, .lib/.dll on MSVC). Copy what is
    # there and say what was not.
    $names = switch ($HOST_OS) {
        "macos"   { @("libssplayer_wgpu.a", "libssplayer_wgpu.dylib") }
        "linux"   { @("libssplayer_wgpu.a", "libssplayer_wgpu.so") }
        "windows" { @("ssplayer_wgpu.lib", "ssplayer_wgpu.dll", "ssplayer_wgpu.dll.lib") }
    }
    $copied = 0
    foreach ($name in $names) {
        $src = Join-Path $SRC_DIR $name
        if (Test-Path $src) {
            Copy-Item -Force $src (Join-Path $LIB_OUT_DIR $name)
            $copied++
        }
    }
    if ($copied -eq 0) { Fail "no library found in target/$($opts.build)" }

    # The header only exists once cbindgen has run, i.e. after an ffi build.
    if ($opts.ffi -eq "yes") {
        $incDir = Join-Path $BIN_DIR "include"
        New-Item -ItemType Directory -Force -Path $incDir > $null
        Copy-Item -Force (Join-Path $ROOT_DIR "libs/ssplayer-wgpu-ffi/include/ssplayer_wgpu.h") $incDir
    }
    Copy-License

    Write-Host ""
    Write-Host "${APP}: done -> bin/libs/$HOST_OS/$HOST_ARCH/ ($copied file(s)), bin/LICENSE.md"
    if ($opts.ffi -eq "yes") { Write-Host "${APP}:      -> bin/include/ssplayer_wgpu.h" }
    Write-Host "${APP}:      (cargo's own output stays in target/$($opts.build)/)"
    exit 0
}

# --- web ------------------------------------------------------------------
$WEB_DIR = Join-Path $ROOT_DIR "examples/web"
# wasm-pack's own output name, at the root where an npm package belongs - this
# face's artifact is a package, not a library file to file away under bin/libs.
$PKG_DIR = Join-Path $ROOT_DIR "pkg"

if (!(Get-Command wasm-pack -ErrorAction SilentlyContinue)) {
    Fail "wasm-pack not found (cargo install wasm-pack)"
}
if (Get-Command rustup -ErrorAction SilentlyContinue) {
    if ((rustup target list --installed) -notcontains "wasm32-unknown-unknown") {
        Fail "the wasm32 target is missing (rustup target add wasm32-unknown-unknown)"
    }
}

# --dev skips wasm-opt, so the output is several times larger. SPEC 14.1's size
# figures are release figures; never quote a --dev build for them.
$wasmProfile = if ($opts.build -eq "debug") { "--dev" } else { "--release" }

# wasm-pack writes the finished package - wasm, JS bindings, .d.ts, LICENSE - so
# its out-dir *is* the collected artifact for this platform; there is nothing for
# Copy-License to add.
Write-Host ">> wasm-pack build (ssplayer-wgpu-ffi, --no-default-features --features web, $($opts.build)) -> pkg"
if (Test-Path $PKG_DIR) { Remove-Item -Recurse -Force $PKG_DIR }
Invoke-Checked "wasm-pack build" {
    & wasm-pack build (Join-Path $ROOT_DIR "libs/ssplayer-wgpu-ffi") `
        --target web $wasmProfile `
        --out-name ssplayer_wgpu `
        --out-dir $PKG_DIR `
        -- --no-default-features --features web
}

if ($opts.deploy -eq "yes") {
    # Only the wasm package: the demo's `.ssab` and atlases belong to
    # deploy-examples.ps1, in both export modes. `wasm/` rather than wasm-pack's
    # `pkg/`, matching where ssplayer-core keeps the same kind of output.
    Write-Host ">> deploying the wasm package -> examples/web/wasm"
    $dest = Join-Path $WEB_DIR "wasm"
    Reset-Dir $dest
    Copy-Item -Recurse -Force (Join-Path $PKG_DIR "*") $dest
}

Write-Host ""
Write-Host "${APP}: done -> pkg/"
if ($opts.deploy -eq "yes") {
    Write-Host "${APP}:      -> examples/web/wasm/"
    Write-Host "${APP}: serve it: (cd examples/web; python3 -m http.server) then open http://localhost:8000"
    Write-Host "${APP}: the demo's .ssab come from scripts/deploy-examples.ps1"
}
