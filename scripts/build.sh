#!/usr/bin/env bash
#
# Build the ssplayer-wgpu library for one platform and collect its artifacts.
#
#   scripts/build.sh                            # host, release
#   scripts/build.sh platform=web build=debug   # wasm for examples/web, fast build
#
# Same shape as the sibling players' build-runtime.sh: build the library, then
# gather the library, its public header and its licence into one project-local
# tree, so release-<platform>.sh packages from a known layout instead of knowing
# where each toolchain drops its output.
#
#   bin/include/ssplayer_wgpu.h                 (ffi=yes, regenerated by cbindgen)
#   bin/LICENSE.md, bin/LICENSE.ja.md, bin/THIRD_PARTY_NOTICES.md
#   bin/libs/<platform>/<arch>/libssplayer_wgpu.{a,dylib,so} | ssplayer_wgpu.{lib,dll}
#   bin/libs/<platform>/<arch>/VERSION          (the SDK release the library links)
#   packages/ssplayer-wgpu/wasm/                (wasm-pack --target web, and VERSION)
#   packages/ssplayer-wgpu/dist/                (tsdown; the npm package is published
#                                                from that directory as it stands)
#   packages/ssplayer-wgpu/docs/                (the documentation, as Markdown)
#   packages/ssplayer-wgpu/skills/ssplayer-wgpu/ (the same pages, as an Agent Skill)
#   examples/web/ssplayer-wgpu/                 (deploy=yes)
#
# Playback data is not this script's business at all: converting the SDK's test
# projects into .ssab -- and building the ssconverter-cli that does it -- is
# scripts/deploy-examples.sh, which also deploys both export modes to the demo.
set -euo pipefail

APP="$(basename "$0")"
ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
BIN_DIR="$ROOT_DIR/bin"

case "${OSTYPE:-}" in
  darwin*)          HOST_OS="macos" ;;
  msys*|cygwin*)    HOST_OS="windows" ;;
  *)                HOST_OS="linux" ;;
esac
HOST_ARCH="$(uname -m)"
[ "$HOST_ARCH" = "aarch64" ] && HOST_ARCH="arm64"

# --- options --------------------------------------------------------------
PLATFORM="host"
ARCH="host"
BUILD="release"
FFI="yes"
DEPLOY="yes"

usage () {
  echo "Usage: $APP [options]"
  echo "$APP options:"
  echo "  platform=<host|web>     Target platform (default: host)"
  echo "                          host = Rust library (+ the C face); web = wasm/js face"
  echo "  arch=<host|universal>   macOS only: universal lipos the arm64 and x86_64"
  echo "                          slices into one library (default: $ARCH)"
  echo "  build=<release|debug>   Build profile (default: $BUILD)"
  echo "  ffi=<yes|no>            host only: also build --features ffi, which regenerates"
  echo "                          libs/ssplayer-wgpu-ffi/include/ssplayer_wgpu.h (default: $FFI)"
  echo "  deploy=<yes|no>         web only: copy the built npm package into examples/web"
  echo "                          (default: $DEPLOY)"
  echo "  -h | --help             Show this help"
  echo ""
  echo "host artifacts are collected under bin/, the web package into"
  echo "packages/ssplayer-wgpu/ (wasm/ + dist/), which is what npm publishes. This is"
  echo "$HOST_OS/$HOST_ARCH and the script does not cross-compile; macos/windows/linux"
  echo "are accepted as aliases for platform=host when they name the host itself."
  echo ""
  echo "arch=universal is the one exception, and only on macOS: both Apple targets"
  echo "come from the same toolchain, so the release ships one library per platform"
  echo "rather than one per Mac."
  echo ""
  echo "Playback data (.ssab) is scripts/deploy-examples.sh, not this script."
}

while [ $# -gt 0 ]; do
  item="$1"
  shift

  case "$item" in
    -h|--help|help)
      usage
      exit 0
      ;;
    *=*)
      key="${item%%=*}"
      value="$(printf '%s' "${item#*=}" | tr '[:upper:]' '[:lower:]')"
      case "$key" in
        platform) PLATFORM="$value" ;;
        arch)     ARCH="$value" ;;
        build)    BUILD="$value" ;;
        ffi)      FFI="$value" ;;
        deploy)   DEPLOY="$value" ;;
        *)
          echo "$APP: unknown option '$key' (see $APP --help)" >&2
          exit 2
          ;;
      esac
      ;;
    *)
      echo "$APP: unknown argument '$item' (options are key=value; see $APP --help)" >&2
      exit 2
      ;;
  esac
done

case "$PLATFORM" in
  host|native)
    PLATFORM="host"
    ;;
  web)
    ;;
  macos|windows|win|linux)
    [ "$PLATFORM" = "win" ] && PLATFORM="windows"
    if [ "$PLATFORM" != "$HOST_OS" ]; then
      echo "$APP: platform=$PLATFORM, but this is $HOST_OS; cross-compilation is not supported" >&2
      exit 2
    fi
    PLATFORM="host"
    ;;
  *)
    echo "$APP: platform must be host or web (got '$PLATFORM')" >&2
    exit 2
    ;;
esac

case "$ARCH" in
  host) ;;
  universal)
    if [ "$PLATFORM" != "host" ]; then
      echo "$APP: arch=universal is for the native library, not platform=$PLATFORM" >&2
      exit 2
    fi
    if [ "$HOST_OS" != "macos" ]; then
      echo "$APP: arch=universal is macOS only (this is $HOST_OS)" >&2
      exit 2
    fi
    ;;
  *)
    echo "$APP: arch must be host or universal (got '$ARCH')" >&2
    exit 2
    ;;
esac

case "$BUILD" in
  release|debug) ;;
  *) echo "$APP: build must be release or debug (got '$BUILD')" >&2; exit 2 ;;
esac
case "$FFI" in
  yes|no) ;;
  *) echo "$APP: ffi must be yes or no (got '$FFI')" >&2; exit 2 ;;
esac
case "$DEPLOY" in
  yes|no) ;;
  *) echo "$APP: deploy must be yes or no (got '$DEPLOY')" >&2; exit 2 ;;
esac

# The SpriteStudio-SDK release this build links: the submodule's tag when it sits
# on one, `local` otherwise. ssplayer-wgpu's build.rs bakes it into the library,
# and VERSION beside the library says it the way the sibling players' does.
SDK_VERSION="$(git -C "$ROOT_DIR/SpriteStudio-SDK" describe --tags --exact-match --match 'v[0-9]*' 2>/dev/null || echo local)"
export SSPLAYER_SDK_VERSION="$SDK_VERSION"

echo "options"
echo "  platform => $PLATFORM"
echo "  build    => $BUILD"
echo "  sdk      => $SDK_VERSION"
[ "$PLATFORM" = "host" ] && echo "  ffi      => $FFI"
[ "$PLATFORM" = "web" ]  && echo "  deploy   => $DEPLOY"
echo ""

# --- preflight ------------------------------------------------------------
# ssruntime / ssab are path dependencies into the submodule, so nothing builds
# without it.
if [ ! -f "$ROOT_DIR/SpriteStudio-SDK/Cargo.toml" ]; then
  echo "$APP: SpriteStudio-SDK submodule is not initialized" >&2
  echo "$APP: run 'git submodule update --init' first" >&2
  exit 1
fi

if ! command -v cargo > /dev/null 2>&1; then
  echo "$APP: cargo not found (install a Rust toolchain: https://rustup.rs)" >&2
  exit 1
fi

# The library's own licence travels with the binaries, not the repository's —
# and so do the dependency notices, since a C or C++ project takes only bin/.
collect_license () {
  mkdir -p "$BIN_DIR"
  cp "$ROOT_DIR/libs/ssplayer-wgpu/LICENSE.md" "$ROOT_DIR/libs/ssplayer-wgpu/LICENSE.ja.md" "$BIN_DIR/"
  cp "$ROOT_DIR/THIRD_PARTY_NOTICES.md" "$BIN_DIR/"
}

# --- host -----------------------------------------------------------------
if [ "$PLATFORM" = "host" ]; then
  PROFILE_FLAG=""
  [ "$BUILD" = "release" ] && PROFILE_FLAG="--release"

  if [ "$ARCH" = "universal" ]; then
    # Both Apple targets, then lipo. Cargo cannot emit a fat library itself, and
    # a release that shipped one library per Mac would be the same source twice.
    for t in aarch64-apple-darwin x86_64-apple-darwin; do
      echo ">> cargo build -p ssplayer-wgpu-ffi --target $t ($BUILD)"
      # shellcheck disable=SC2086
      ( cd "$ROOT_DIR" && cargo build -p ssplayer-wgpu-ffi --target "$t" $PROFILE_FLAG )
    done

    LIB_OUT_DIR="$BIN_DIR/libs/macos/universal"
    echo ">> lipo -> bin/libs/macos/universal"
    rm -rf "$LIB_OUT_DIR"; mkdir -p "$LIB_OUT_DIR"
    for lib in libssplayer_wgpu.a libssplayer_wgpu.dylib; do
      a="$ROOT_DIR/target/aarch64-apple-darwin/$BUILD/$lib"
      x="$ROOT_DIR/target/x86_64-apple-darwin/$BUILD/$lib"
      if [ -f "$a" ] && [ -f "$x" ]; then
        lipo -create "$a" "$x" -output "$LIB_OUT_DIR/$lib"
      fi
    done
    printf '%s\n' "$SDK_VERSION" > "$LIB_OUT_DIR/VERSION"

    mkdir -p "$BIN_DIR/include"
    cp "$ROOT_DIR/libs/ssplayer-wgpu-ffi/include/ssplayer_wgpu.h" "$BIN_DIR/include/"
    collect_license

    echo ""
    echo "$APP: done -> bin/libs/macos/universal/ ($(ls -1 "$LIB_OUT_DIR" | wc -l | tr -d ' ') file(s)), bin/LICENSE.md + bin/LICENSE.ja.md + bin/THIRD_PARTY_NOTICES.md"
    echo "$APP:      -> bin/include/ssplayer_wgpu.h"
    exit 0
  fi

  echo ">> cargo build -p ssplayer-wgpu-ffi ($BUILD)"
  # Unquoted on purpose: PROFILE_FLAG is one token or nothing.
  # shellcheck disable=SC2086
  ( cd "$ROOT_DIR" && cargo build -p ssplayer-wgpu-ffi --no-default-features --features embedded $PROFILE_FLAG )

  if [ "$FFI" = "yes" ]; then
    # No default command compiles src/ffi.rs or src/host.rs, so the C face rots
    # silently unless it is built explicitly. build.rs runs cbindgen in the same
    # pass, which is what keeps include/ssplayer_wgpu.h in step with the API.
    echo ">> cargo build -p ssplayer-wgpu-ffi ($BUILD) — regenerates include/ssplayer_wgpu.h"
    # shellcheck disable=SC2086
    ( cd "$ROOT_DIR" && cargo build -p ssplayer-wgpu-ffi $PROFILE_FLAG )
  fi

  # --- collect ------------------------------------------------------------
  SRC_DIR="$ROOT_DIR/target/$BUILD"
  LIB_OUT_DIR="$BIN_DIR/libs/$HOST_OS/$HOST_ARCH"
  echo ">> collecting artifacts from target/$BUILD -> bin/libs/$HOST_OS/$HOST_ARCH"
  rm -rf "$LIB_OUT_DIR"; mkdir -p "$LIB_OUT_DIR"

  # cargo emits every crate-type each build, but which names appear is the
  # platform's business (staticlib + cdylib, .lib/.dll on MSVC). Copy what is
  # there and say what was not.
  copied=0
  copy_lib () { # <file-name>
    if [ -f "$SRC_DIR/$1" ]; then
      cp "$SRC_DIR/$1" "$LIB_OUT_DIR/$1"
      copied=$((copied + 1))
    fi
  }
  case "$HOST_OS" in
    macos)
      copy_lib "libssplayer_wgpu.a"
      copy_lib "libssplayer_wgpu.dylib"
      ;;
    linux)
      copy_lib "libssplayer_wgpu.a"
      copy_lib "libssplayer_wgpu.so"
      ;;
    windows)
      copy_lib "ssplayer_wgpu.lib"
      copy_lib "ssplayer_wgpu.dll"
      copy_lib "ssplayer_wgpu.dll.lib"
      ;;
  esac
  if [ "$copied" -eq 0 ]; then
    echo "$APP: no library found in target/$BUILD" >&2
    exit 1
  fi
  printf '%s\n' "$SDK_VERSION" > "$LIB_OUT_DIR/VERSION"

  # The header only exists once cbindgen has run, i.e. after an ffi build.
  if [ "$FFI" = "yes" ]; then
    mkdir -p "$BIN_DIR/include"
    cp "$ROOT_DIR/libs/ssplayer-wgpu-ffi/include/ssplayer_wgpu.h" "$BIN_DIR/include/"
  fi
  collect_license

  echo ""
  echo "$APP: done -> bin/libs/$HOST_OS/$HOST_ARCH/ ($copied file(s)), bin/LICENSE.md + bin/LICENSE.ja.md + bin/THIRD_PARTY_NOTICES.md"
  [ "$FFI" = "yes" ] && echo "$APP:      -> bin/include/ssplayer_wgpu.h"
  echo "$APP:      (cargo's own output stays in target/$BUILD/)"
  exit 0
fi

# --- web ------------------------------------------------------------------
WEB_DIR="$ROOT_DIR/examples/web"
# The npm package is checked in and published from where it sits: package.json,
# the TypeScript layer and the READMEs are sources, `wasm/` and `dist/` are what
# this script puts beside them. There is no separate collect directory, because
# for this face the *package directory* is the artifact.
PKG_DIR="$ROOT_DIR/packages/ssplayer-wgpu"

if ! command -v wasm-pack > /dev/null 2>&1; then
  echo "$APP: wasm-pack not found (cargo install wasm-pack)" >&2
  exit 1
fi
if command -v rustup > /dev/null 2>&1; then
  if ! rustup target list --installed | grep -q '^wasm32-unknown-unknown$'; then
    echo "$APP: the wasm32 target is missing (rustup target add wasm32-unknown-unknown)" >&2
    exit 1
  fi
fi
# The js layer (@spritestudio/ssplayer-wgpu's `.` and `./element` entry points) is
# TypeScript built by tsdown, so the web face needs node as well as cargo. pnpm
# specifically: the version is pinned in the package's `packageManager` field and
# the lockfile is committed, so `corepack enable` is enough to get the right one.
if ! command -v pnpm > /dev/null 2>&1; then
  echo "$APP: pnpm not found (corepack enable, or npm i -g pnpm) -- needed to build the js layer" >&2
  exit 1
fi

WASM_PROFILE="--release"
if [ "$BUILD" = "debug" ]; then
  # --dev skips wasm-opt, so the output is several times larger. Size
  # figures are release figures; never quote a --dev build for them.
  WASM_PROFILE="--dev"
fi

# wasm-pack writes the wasm, the JS bindings and the .d.ts; they are the package's
# runtime, imported by dist/ as `../wasm/ssplayer_wgpu.js` and pinnable on a CDN
# through the `./wasm/*` export.
echo ">> wasm-pack build (ssplayer-wgpu-ffi, --no-default-features --features web, $BUILD) -> packages/ssplayer-wgpu/wasm"
rm -rf "$PKG_DIR/wasm"
wasm-pack build "$ROOT_DIR/libs/ssplayer-wgpu-ffi" \
  --target web "$WASM_PROFILE" \
  --out-name ssplayer_wgpu \
  --out-dir "$PKG_DIR/wasm" \
  -- --no-default-features --features web

# wasm-pack also writes a package.json naming the *crate* (ssplayer-wgpu-ffi) and
# a `.gitignore` holding `*`. Both are wrong inside a package whose manifest is
# checked in one directory up, and a stray second package.json is exactly the kind
# of thing a publish tool picks the wrong one of. The licence is at the package
# root already.
rm -f "$PKG_DIR/wasm/package.json" "$PKG_DIR/wasm/.gitignore" "$PKG_DIR/wasm/LICENSE.md" "$PKG_DIR/wasm/LICENSE.ja.md" "$PKG_DIR/wasm/README.md"
printf '%s\n' "$SDK_VERSION" > "$PKG_DIR/wasm/VERSION"

# The wasm compiles in wgpu and every crate under it, so the package carries their
# notices. Copied rather than committed a second time, so it cannot drift from the
# root file scripts/generate-licenses.sh writes; `files` in package.json lists it,
# and the prepack check refuses to publish without it.
cp "$ROOT_DIR/THIRD_PARTY_NOTICES.md" "$PKG_DIR/"

# The documentation of this build, read offline beside it (scripts/copy-docs.mjs),
# with docs/README.md as the folder's front door, and the same pages as the
# agent skill skills/ssplayer-wgpu/. `files` lists both.
node "$ROOT_DIR/scripts/copy-docs.mjs" "$PKG_DIR/docs" "$PKG_DIR/skills/ssplayer-wgpu"
cp "$ROOT_DIR/scripts/release-docs/npm-README.md" "$PKG_DIR/docs/README.md"

echo ">> pnpm install + build (tsdown) -> packages/ssplayer-wgpu/dist"
( cd "$PKG_DIR" && pnpm install --frozen-lockfile && pnpm run build )

if [ "$DEPLOY" = "yes" ]; then
  # The whole package, not just the wasm: the demo imports the same `dist/` an npm
  # consumer does, so the element and the shared-context helper are exercised as
  # shipped instead of from a second copy that can drift. Layout preserved, since
  # dist/ reaches its runtime through `../wasm/`.
  echo ">> deploying the package -> examples/web/ssplayer-wgpu"
  rm -rf "$WEB_DIR/ssplayer-wgpu"
  mkdir -p "$WEB_DIR/ssplayer-wgpu"
  cp -R "$PKG_DIR/dist" "$PKG_DIR/wasm" "$WEB_DIR/ssplayer-wgpu/"
  cp "$PKG_DIR/package.json" "$PKG_DIR/LICENSE.md" "$WEB_DIR/ssplayer-wgpu/"
fi

echo ""
echo "$APP: done -> packages/ssplayer-wgpu/ (wasm/ + dist/ + docs/)"
if [ "$DEPLOY" = "yes" ]; then
  echo "$APP:      -> examples/web/ssplayer-wgpu/"
  echo "$APP: serve it: (cd examples/web && python3 -m http.server --bind 127.0.0.1) then open http://localhost:8000"
  echo "$APP: the demo's .ssab come from scripts/deploy-examples.sh"
fi
