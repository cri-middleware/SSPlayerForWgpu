#!/usr/bin/env bash
#
# Build the ssplayer-wgpu library for one platform and collect its artifacts.
#
#   scripts/build.sh                            # host, release
#   scripts/build.sh platform=web build=debug   # wasm for examples/web, fast build
#
# Same shape as the sibling players' build-runtime.sh: build the library, then
# gather the library, its public header and its licence into one project-local
# tree, so release-<platform>.sh packages from a known layout instead of knowing
# where each toolchain drops its output.
#
#   bin/include/ssplayer_wgpu.h                 (ffi=yes, regenerated by cbindgen)
#   bin/LICENSE.md
#   bin/libs/<platform>/<arch>/libssplayer_wgpu.{a,dylib,so} | ssplayer_wgpu.{lib,dll}
#   pkg/                                        (wasm-pack --target web; its own
#                                                convention, and already a package)
#   examples/web/wasm/                          (deploy=yes)
#
# Playback data is not this script's business at all: converting the SDK's test
# projects into .ssab -- and building the ssconverter-cli that does it -- is
# scripts/deploy-examples.sh, which also deploys both export modes to the demo.
set -euo pipefail

APP="$(basename "$0")"
ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
BIN_DIR="$ROOT_DIR/bin"

case "${OSTYPE:-}" in
  darwin*)          HOST_OS="macos" ;;
  msys*|cygwin*)    HOST_OS="windows" ;;
  *)                HOST_OS="linux" ;;
esac
HOST_ARCH="$(uname -m)"
[ "$HOST_ARCH" = "aarch64" ] && HOST_ARCH="arm64"

# --- options --------------------------------------------------------------
PLATFORM="host"
BUILD="release"
FFI="yes"
DEPLOY="yes"

usage () {
  echo "Usage: $APP [options]"
  echo "$APP options:"
  echo "  platform=<host|web>     Target platform (default: host)"
  echo "                          host = Rust library (+ the C face); web = wasm/js face"
  echo "  build=<release|debug>   Build profile (default: $BUILD)"
  echo "  ffi=<yes|no>            host only: also build --features ffi, which regenerates"
  echo "                          libs/ssplayer-wgpu/include/ssplayer_wgpu.h (default: $FFI)"
  echo "  deploy=<yes|no>         web only: copy the wasm package into examples/web"
  echo "                          (default: $DEPLOY)"
  echo "  -h | --help             Show this help"
  echo ""
  echo "host artifacts are collected under bin/, the web package into pkg/. This is"
  echo "$HOST_OS/$HOST_ARCH and the script does not cross-compile; macos/windows/linux"
  echo "are accepted as aliases for platform=host when they name the host itself."
  echo ""
  echo "Playback data (.ssab) is scripts/deploy-examples.sh, not this script."
}

while [ $# -gt 0 ]; do
  item="$1"
  shift

  case "$item" in
    -h|--help|help)
      usage
      exit 0
      ;;
    *=*)
      key="${item%%=*}"
      value="$(printf '%s' "${item#*=}" | tr '[:upper:]' '[:lower:]')"
      case "$key" in
        platform) PLATFORM="$value" ;;
        build)    BUILD="$value" ;;
        ffi)      FFI="$value" ;;
        deploy)   DEPLOY="$value" ;;
        *)
          echo "$APP: unknown option '$key' (see $APP --help)" >&2
          exit 2
          ;;
      esac
      ;;
    *)
      echo "$APP: unknown argument '$item' (options are key=value; see $APP --help)" >&2
      exit 2
      ;;
  esac
done

case "$PLATFORM" in
  host|native)
    PLATFORM="host"
    ;;
  web)
    ;;
  macos|windows|win|linux)
    [ "$PLATFORM" = "win" ] && PLATFORM="windows"
    if [ "$PLATFORM" != "$HOST_OS" ]; then
      echo "$APP: platform=$PLATFORM, but this is $HOST_OS; cross-compilation is not supported" >&2
      exit 2
    fi
    PLATFORM="host"
    ;;
  *)
    echo "$APP: platform must be host or web (got '$PLATFORM')" >&2
    exit 2
    ;;
esac

case "$BUILD" in
  release|debug) ;;
  *) echo "$APP: build must be release or debug (got '$BUILD')" >&2; exit 2 ;;
esac
case "$FFI" in
  yes|no) ;;
  *) echo "$APP: ffi must be yes or no (got '$FFI')" >&2; exit 2 ;;
esac
case "$DEPLOY" in
  yes|no) ;;
  *) echo "$APP: deploy must be yes or no (got '$DEPLOY')" >&2; exit 2 ;;
esac

echo "options"
echo "  platform => $PLATFORM"
echo "  build    => $BUILD"
[ "$PLATFORM" = "host" ] && echo "  ffi      => $FFI"
[ "$PLATFORM" = "web" ]  && echo "  deploy   => $DEPLOY"
echo ""

# --- preflight ------------------------------------------------------------
# ssruntime / ssab are path dependencies into the submodule, so nothing builds
# without it.
if [ ! -f "$ROOT_DIR/SpriteStudio-SDK/Cargo.toml" ]; then
  echo "$APP: SpriteStudio-SDK submodule is not initialized" >&2
  echo "$APP: run 'git submodule update --init' first" >&2
  exit 1
fi

if ! command -v cargo > /dev/null 2>&1; then
  echo "$APP: cargo not found (install a Rust toolchain: https://rustup.rs)" >&2
  exit 1
fi

# The library's own licence travels with the binaries, not the repository's.
collect_license () {
  mkdir -p "$BIN_DIR"
  cp "$ROOT_DIR/libs/ssplayer-wgpu/LICENSE.md" "$BIN_DIR/"
}

# --- host -----------------------------------------------------------------
if [ "$PLATFORM" = "host" ]; then
  PROFILE_FLAG=""
  [ "$BUILD" = "release" ] && PROFILE_FLAG="--release"

  echo ">> cargo build -p ssplayer-wgpu ($BUILD)"
  # Unquoted on purpose: PROFILE_FLAG is one token or nothing.
  # shellcheck disable=SC2086
  ( cd "$ROOT_DIR" && cargo build -p ssplayer-wgpu $PROFILE_FLAG )

  if [ "$FFI" = "yes" ]; then
    # No default command compiles src/ffi.rs or src/host.rs, so the C face rots
    # silently unless it is built explicitly. build.rs runs cbindgen in the same
    # pass, which is what keeps include/ssplayer_wgpu.h in step with the API.
    echo ">> cargo build -p ssplayer-wgpu --features ffi ($BUILD) — regenerates include/ssplayer_wgpu.h"
    # shellcheck disable=SC2086
    ( cd "$ROOT_DIR" && cargo build -p ssplayer-wgpu --features ffi $PROFILE_FLAG )
  fi

  # --- collect ------------------------------------------------------------
  SRC_DIR="$ROOT_DIR/target/$BUILD"
  LIB_OUT_DIR="$BIN_DIR/libs/$HOST_OS/$HOST_ARCH"
  echo ">> collecting artifacts from target/$BUILD -> bin/libs/$HOST_OS/$HOST_ARCH"
  rm -rf "$LIB_OUT_DIR"; mkdir -p "$LIB_OUT_DIR"

  # cargo emits every crate-type each build, but which names appear is the
  # platform's business (staticlib + cdylib, .lib/.dll on MSVC). Copy what is
  # there and say what was not.
  copied=0
  copy_lib () { # <file-name>
    if [ -f "$SRC_DIR/$1" ]; then
      cp "$SRC_DIR/$1" "$LIB_OUT_DIR/$1"
      copied=$((copied + 1))
    fi
  }
  case "$HOST_OS" in
    macos)
      copy_lib "libssplayer_wgpu.a"
      copy_lib "libssplayer_wgpu.dylib"
      ;;
    linux)
      copy_lib "libssplayer_wgpu.a"
      copy_lib "libssplayer_wgpu.so"
      ;;
    windows)
      copy_lib "ssplayer_wgpu.lib"
      copy_lib "ssplayer_wgpu.dll"
      copy_lib "ssplayer_wgpu.dll.lib"
      ;;
  esac
  if [ "$copied" -eq 0 ]; then
    echo "$APP: no library found in target/$BUILD" >&2
    exit 1
  fi

  # The header only exists once cbindgen has run, i.e. after an ffi build.
  if [ "$FFI" = "yes" ]; then
    mkdir -p "$BIN_DIR/include"
    cp "$ROOT_DIR/libs/ssplayer-wgpu/include/ssplayer_wgpu.h" "$BIN_DIR/include/"
  fi
  collect_license

  echo ""
  echo "$APP: done -> bin/libs/$HOST_OS/$HOST_ARCH/ ($copied file(s)), bin/LICENSE.md"
  [ "$FFI" = "yes" ] && echo "$APP:      -> bin/include/ssplayer_wgpu.h"
  echo "$APP:      (cargo's own output stays in target/$BUILD/)"
  exit 0
fi

# --- web ------------------------------------------------------------------
WEB_DIR="$ROOT_DIR/examples/web"
# wasm-pack's own output name, at the root where an npm package belongs — this
# face's artifact is a package, not a library file to file away under bin/libs.
PKG_DIR="$ROOT_DIR/pkg"

if ! command -v wasm-pack > /dev/null 2>&1; then
  echo "$APP: wasm-pack not found (cargo install wasm-pack)" >&2
  exit 1
fi
if command -v rustup > /dev/null 2>&1; then
  if ! rustup target list --installed | grep -q '^wasm32-unknown-unknown$'; then
    echo "$APP: the wasm32 target is missing (rustup target add wasm32-unknown-unknown)" >&2
    exit 1
  fi
fi

WASM_PROFILE="--release"
if [ "$BUILD" = "debug" ]; then
  # --dev skips wasm-opt, so the output is several times larger. SPEC §14.1's
  # size figures are release figures; never quote a --dev build for them.
  WASM_PROFILE="--dev"
fi

# wasm-pack writes the finished package — wasm, JS bindings, .d.ts, LICENSE — so
# its out-dir *is* the collected artifact for this platform; there is nothing for
# collect_license to add.
echo ">> wasm-pack build (ssplayer-wgpu, --no-default-features --features web, $BUILD) -> pkg"
rm -rf "$PKG_DIR"
wasm-pack build "$ROOT_DIR/libs/ssplayer-wgpu" \
  --target web "$WASM_PROFILE" \
  --out-name ssplayer_wgpu \
  --out-dir "$PKG_DIR" \
  -- --no-default-features --features web

if [ "$DEPLOY" = "yes" ]; then
  # Only the wasm package: the demo's `.ssab` and atlases belong to
  # deploy-examples.sh, in both export modes. `wasm/` rather than wasm-pack's
  # `pkg/`, matching where ssplayer-core keeps the same kind of output.
  echo ">> deploying the wasm package -> examples/web/wasm"
  rm -rf "$WEB_DIR/wasm"
  mkdir -p "$WEB_DIR/wasm"
  cp -R "$PKG_DIR/." "$WEB_DIR/wasm/"
fi

echo ""
echo "$APP: done -> pkg/"
if [ "$DEPLOY" = "yes" ]; then
  echo "$APP:      -> examples/web/wasm/"
  echo "$APP: serve it: (cd examples/web && python3 -m http.server) then open http://localhost:8000"
  echo "$APP: the demo's .ssab come from scripts/deploy-examples.sh"
fi
