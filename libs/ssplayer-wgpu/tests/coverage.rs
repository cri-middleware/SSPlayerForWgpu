//! The coverage-bitmap mask backend, measured against the
//! stencil one.
//!
//! The two backends implement the same semantics from opposite ends, so what
//! these ask is not "does it draw something" but "does it draw what the stencil
//! draws". A host picks a backend because of what its render pass can lend, never
//! because of the animation — so the same `.ssab` has to survive the choice.
//!
//! Skips itself when no GPU adapter is present, like the other rendering tests.

use ssplayer_wgpu::{MaskBackend, SSPlayer, SSRenderer, SSScene, SceneConfig};
use std::path::Path;

/// How much bigger than the pack's own canvas to render.
///
/// The target is sized from `canvas_size` rather than fixed, because a fixed one
/// crops: these fixtures are up to 1000 px wide, and comparing the 256 px in the
/// middle of them would agree about a corner of the picture and call it parity.
/// The margin catches content authored to enter from off-canvas.
const CANVAS_MARGIN: f32 = 1.8;
const COLOR_FORMAT: wgpu::TextureFormat = wgpu::TextureFormat::Rgba8Unorm;
const STENCIL_FORMAT: wgpu::TextureFormat = wgpu::TextureFormat::Depth24PlusStencil8;

/// A fixture: where the pack lives, which animation, and how far to advance.
///
/// `assets/overall` is generated by `deploy-examples`; `assets/Mask` is the
/// reference Player's mask project, which this repository's SDK submodule does
/// not carry — so those two are skipped rather than failing when absent.
const FIXTURES: [(&str, u32); 4] = [("overall/Mask", 4), ("Mask/True_Light", 8), ("Mask/Walk_Gate", 12), ("Mask/Into_Gate", 10)];

fn assets() -> &'static str {
    concat!(env!("CARGO_MANIFEST_DIR"), "/../../assets")
}

/// Render one fixture with one backend and read the pixels back, along with the
/// size it was rendered at.
fn render(device: &wgpu::Device, queue: &wgpu::Queue, fixture: &str, frames: u32, mask: MaskBackend) -> (Vec<u8>, u32, u32) {
    let path = format!("{}/{fixture}.ssab", assets());

    let mut renderer = SSRenderer::new(device);
    let stencil_format = (mask == MaskBackend::Stencil).then_some(STENCIL_FORMAT);
    let mut scene = SSScene::new(device, &SceneConfig { color_format: COLOR_FORMAT, stencil_format, mask });

    let mut player = SSPlayer::new();
    player.load(&path).unwrap();
    let anim = player.animation_names().unwrap()[0].clone();
    player.set_animation(&anim).unwrap();
    player.play();

    let (cw, ch) = player.canvas_size().unwrap_or((512.0, 512.0));
    let (w, h) = ((cw * CANVAS_MARGIN).round().max(64.0) as u32, (ch * CANVAS_MARGIN).round().max(64.0) as u32);

    scene.set_viewport(queue, w as f32, h as f32, false);
    for _ in 0..frames {
        scene.update(&mut renderer, device, queue, 1.0 / 60.0, &mut [&mut player]);
    }

    let color = device.create_texture(&wgpu::TextureDescriptor {
        label: Some("offscreen color"),
        size: wgpu::Extent3d { width: w, height: h, depth_or_array_layers: 1 },
        mip_level_count: 1,
        sample_count: 1,
        dimension: wgpu::TextureDimension::D2,
        format: COLOR_FORMAT,
        usage: wgpu::TextureUsages::RENDER_ATTACHMENT | wgpu::TextureUsages::COPY_SRC,
        view_formats: &[],
    });
    let color_view = color.create_view(&wgpu::TextureViewDescriptor::default());
    let depth_view = stencil_format.map(|format| {
        device
            .create_texture(&wgpu::TextureDescriptor {
                label: Some("offscreen stencil"),
                size: wgpu::Extent3d { width: w, height: h, depth_or_array_layers: 1 },
                mip_level_count: 1,
                sample_count: 1,
                dimension: wgpu::TextureDimension::D2,
                format,
                usage: wgpu::TextureUsages::RENDER_ATTACHMENT,
                view_formats: &[],
            })
            .create_view(&wgpu::TextureViewDescriptor::default())
    });
    // `copy_texture_to_buffer` wants rows aligned to 256 bytes, and these targets
    // are sized from the pack rather than chosen to divide evenly.
    let bytes_per_row = (w * 4).div_ceil(256) * 256;
    let readback = device.create_buffer(&wgpu::BufferDescriptor { label: Some("readback"), size: (bytes_per_row * h) as u64, usage: wgpu::BufferUsages::MAP_READ | wgpu::BufferUsages::COPY_DST, mapped_at_creation: false });

    let mut encoder = device.create_command_encoder(&wgpu::CommandEncoderDescriptor { label: None });
    // Between `update` and `draw`, on the same encoder — which is what makes the
    // bitmap this frame's rather than the last one's.
    scene.encode_mask_coverage(&mut renderer, device, &mut encoder);
    {
        let mut rpass = encoder.begin_render_pass(&wgpu::RenderPassDescriptor {
            label: None,
            color_attachments: &[Some(wgpu::RenderPassColorAttachment {
                view: &color_view,
                resolve_target: None,
                ops: wgpu::Operations { load: wgpu::LoadOp::Clear(wgpu::Color { r: 0.0, g: 0.0, b: 0.0, a: 1.0 }), store: wgpu::StoreOp::Store },
                depth_slice: None,
            })],
            depth_stencil_attachment: depth_view.as_ref().map(|view| wgpu::RenderPassDepthStencilAttachment {
                view,
                depth_ops: Some(wgpu::Operations { load: wgpu::LoadOp::Clear(1.0), store: wgpu::StoreOp::Store }),
                stencil_ops: Some(wgpu::Operations { load: wgpu::LoadOp::Clear(0), store: wgpu::StoreOp::Store }),
            }),
            timestamp_writes: None,
            occlusion_query_set: None,
            multiview_mask: None,
        });
        scene.draw(&renderer, &mut rpass);
    }
    encoder.copy_texture_to_buffer(
        wgpu::TexelCopyTextureInfo { texture: &color, mip_level: 0, origin: wgpu::Origin3d::ZERO, aspect: wgpu::TextureAspect::All },
        wgpu::TexelCopyBufferInfo { buffer: &readback, layout: wgpu::TexelCopyBufferLayout { offset: 0, bytes_per_row: Some(bytes_per_row), rows_per_image: Some(h) } },
        wgpu::Extent3d { width: w, height: h, depth_or_array_layers: 1 },
    );
    queue.submit(std::iter::once(encoder.finish()));

    let (tx, rx) = std::sync::mpsc::channel();
    readback.slice(..).map_async(wgpu::MapMode::Read, move |r| {
        let _ = tx.send(r);
    });
    device.poll(wgpu::PollType::Wait { submission_index: None, timeout: None }).unwrap();
    rx.recv().unwrap().unwrap();
    let padded = readback.slice(..).get_mapped_range().to_vec();
    readback.unmap();

    // Drop the row padding the copy alignment demanded.
    let mut tight = Vec::with_capacity((w * h * 4) as usize);
    for row in 0..h {
        let start = (row * bytes_per_row) as usize;
        tight.extend_from_slice(&padded[start..start + (w * 4) as usize]);
    }
    (tight, w, h)
}

fn drawn_pixels(rgba: &[u8]) -> usize {
    rgba.as_chunks::<4>().0.iter().filter(|p| p[0] > 8 || p[1] > 8 || p[2] > 8).count()
}

/// Pixels differing beyond `tolerance`, and the worst channel delta seen.
///
/// Not an exact comparison on purpose: the backends rasterise coverage into
/// different things — the hardware stencil at target resolution, a bitmap at its
/// own — so their mask *edges* land on slightly different pixels. The interiors
/// are what have to agree.
fn differing(a: &[u8], b: &[u8], tolerance: u8) -> (usize, u8) {
    let mut count = 0;
    let mut worst = 0u8;
    for (pa, pb) in a.as_chunks::<4>().0.iter().zip(b.as_chunks::<4>().0.iter()) {
        let delta = pa.iter().zip(pb).map(|(x, y)| x.abs_diff(*y)).max().unwrap_or(0);
        worst = worst.max(delta);
        if delta > tolerance {
            count += 1;
        }
    }
    (count, worst)
}

/// A device, or `None` when the machine has no adapter to give.
fn gpu() -> Option<(wgpu::Device, wgpu::Queue)> {
    let instance = wgpu::Instance::new(wgpu::InstanceDescriptor::new_without_display_handle());
    let adapter = pollster::block_on(instance.request_adapter(&wgpu::RequestAdapterOptions { power_preference: wgpu::PowerPreference::default(), compatible_surface: None, force_fallback_adapter: false })).ok()?;
    let (device, queue) = pollster::block_on(adapter.request_device(&wgpu::DeviceDescriptor::default())).ok()?;
    Some((device, queue))
}

/// Fixtures that are actually on disk. `assets/Mask` needs a manual conversion,
/// so its absence skips rather than fails.
fn present() -> Vec<(&'static str, u32)> {
    FIXTURES.into_iter().filter(|(fixture, _)| Path::new(&format!("{}/{fixture}.ssab", assets())).exists()).collect()
}

#[test]
fn coverage_masks_without_a_stencil_attachment() {
    let Some((device, queue)) = gpu() else {
        eprintln!("no GPU adapter available, skipping");
        return;
    };
    for (fixture, frames) in present() {
        let (pixels, _, _) = render(&device, &queue, fixture, frames, MaskBackend::Coverage);
        assert!(drawn_pixels(&pixels) > 0, "{fixture} drew nothing under the coverage backend");
    }
}

#[test]
fn coverage_and_stencil_agree() {
    let Some((device, queue)) = gpu() else {
        eprintln!("no GPU adapter available, skipping");
        return;
    };
    for (fixture, frames) in present() {
        let (stencil, w, h) = render(&device, &queue, fixture, frames, MaskBackend::Stencil);
        let (coverage, _, _) = render(&device, &queue, fixture, frames, MaskBackend::Coverage);

        // Counts alone have hidden real mask regressions before, so this leaves a
        // way to look: `SS_COVERAGE_DUMP=<dir> cargo test --test coverage`.
        if let Ok(dir) = std::env::var("SS_COVERAGE_DUMP") {
            let name = fixture.replace('/', "-");
            let _ = std::fs::create_dir_all(&dir);
            for (suffix, pixels) in [("stencil", &stencil), ("coverage", &coverage)] {
                let _ = image::RgbaImage::from_raw(w, h, pixels.clone()).unwrap().save(format!("{dir}/{name}-{suffix}.png"));
            }
        }

        let stencil_drawn = drawn_pixels(&stencil);
        assert!(stencil_drawn > 0, "{fixture} drew nothing under the stencil backend — the comparison would be vacuous");

        let (differing, worst) = differing(&stencil, &coverage, 8);
        // A few per cent of the drawn area is mask edge, where the two
        // rasterisations genuinely disagree. Much beyond that and it is the mask
        // itself that differs, not its outline.
        let budget = stencil_drawn / 20;
        assert!(differing <= budget, "{fixture}: {differing} pixels differ (worst channel delta {worst}), over the {budget} the edges are allowed");
    }
}

#[test]
fn a_frame_without_masks_rasterises_no_coverage() {
    let Some((device, queue)) = gpu() else {
        eprintln!("no GPU adapter available, skipping");
        return;
    };
    let path = format!("{}/overall/Basic.ssab", assets());
    if !Path::new(&path).exists() {
        return;
    }

    let mut renderer = SSRenderer::new(&device);
    let mut scene = SSScene::new(&device, &SceneConfig { color_format: COLOR_FORMAT, stencil_format: None, mask: MaskBackend::Coverage });
    let mut player = SSPlayer::new();
    player.load(&path).unwrap();
    let anim = player.animation_names().unwrap()[0].clone();
    player.set_animation(&anim).unwrap();

    scene.set_viewport(&queue, 512.0, 512.0, false);
    scene.update(&mut renderer, &device, &queue, 0.0, &mut [&mut player]);
    let mut encoder = device.create_command_encoder(&Default::default());
    scene.encode_mask_coverage(&mut renderer, &device, &mut encoder);

    assert_eq!(scene.stats().coverage_layers, 0, "an animation with no mask parts should rasterise no coverage");
}
